#Arithmetic Operators
x=5
y=7
print("Sum: ",x+y)
print("Diff: ",x-y)
print("Div: ",round(x/y,2))
print("FllorDiv: ",(x//y))
print("Mul: ",x*y)
print("sqr: ",x**y)
print("mod: ",x%y)

#Comparison Operators
print(x==y)
print(x!=y)
print(x>y)
print(x<y)
print(x>=y)
print(x<=y)

#Logical Operators
print("and operator:",x>y and x<y)
print("Or operator:",x>y or x<y)
print("Not operator:",not(x>y))

#Assignment Operators
x+=2
print("Updated x value: ",x)
x-=2
